#!/usr/bin/env bash
# 把 kernels/（nightly 的 nvptx64-nvidia-cuda 目标）编成 PTX，产出两份提交进仓库：
#   crates/pagesift-gpu/ptx/kernels_sm70.ptx  rustc 原样输出（.target sm_70），给算力 ≥ 7.0 的卡
#   crates/pagesift-gpu/ptx/kernels_sm61.ptx  只把文件头的 .target 改成 sm_61，给 Pascal（6.1、6.2）
# rustc 的 nvptx 目标最低只到 sm_70；内核里不用 Volta 才有的指令，改文件头后 Pascal 的驱动能 JIT。
# 下面会检查 PTX 里没有 sm_70 才有的指令，有就失败。
#
#   scripts/build_kernels.sh
#
# 环境变量：
#   NVPTX_HOME          nightly 工具链所在目录（默认 /mnt/d/nvptx-exp，里面有 rustup/ 和 cargo/）
#   KERNELS_TARGET_DIR  编译目录（默认 $NVPTX_HOME/target-kernels，不放进仓库）
# 改了内核要同时提交两份 PTX；主程序（stable）用 include_str! 嵌入，不需要 nightly。
set -euo pipefail
cd "$(dirname "$0")/.."
NVPTX_HOME=${NVPTX_HOME:-/mnt/d/nvptx-exp}
export RUSTUP_HOME=$NVPTX_HOME/rustup CARGO_HOME=$NVPTX_HOME/cargo
export CARGO_TARGET_DIR=${KERNELS_TARGET_DIR:-$NVPTX_HOME/target-kernels}
cargo=$CARGO_HOME/bin/cargo
rustc=$CARGO_HOME/bin/rustc
[ -x "$cargo" ] || { echo "找不到 $cargo：按 $NVPTX_HOME/README.md 装 nightly 和 nvptx64-nvidia-cuda 目标" >&2; exit 1; }

(cd kernels && "$cargo" +nightly build --release --locked --target nvptx64-nvidia-cuda -Z build-std=core -j 4)
src=$CARGO_TARGET_DIR/nvptx64-nvidia-cuda/release/pagesift_kernels.ptx
grep -qx '\.target sm_70' "$src" || { echo "$src 的 .target 不是 sm_70：rustc 的默认架构变了，先核对再改脚本" >&2; exit 1; }

# sm_70 以后才有的 PTX 指令：出现了就说明 rustc/LLVM 生成了 Pascal 不认的代码，改文件头的路子不再成立
if grep -nE '\b(shfl\.sync|vote\.sync|match\.(any|all)|bar\.warp\.sync|barrier\.sync|activemask|nanosleep|redux\.sync|wmma\.|mma\.sync|cp\.async|elect\.sync)\b' "$src"; then
    echo "PTX 里有 sm_70 才有的指令（见上），sm_61 版不能用" >&2; exit 1
fi

out=crates/pagesift-gpu/ptx
mkdir -p "$out"
ver=$("$rustc" +nightly -V)
# 文件头注释只能是 ASCII：ptxas 遇到非 ASCII 字符直接报错（"Unexpected non-ASCII character"）
{ echo "// Generated by scripts/build_kernels.sh from kernels/, do not edit. Toolchain: $ver"; cat "$src"; } > "$out/kernels_sm70.ptx"
if LC_ALL=C grep -qP '[^\x00-\x7F]' "$out/kernels_sm70.ptx"; then echo "PTX 里有非 ASCII 字符" >&2; exit 1; fi
# 只改 .target，.version 保持 rustc 给的（7.0）：PTX ISA 版本只约束语法，新版本照样能面向 sm_61；
# 降到 6.0 不行，rustc 给 panic 路径的函数标了 .noreturn，那要 ISA 6.4 起（驱动 JIT 时报错）
sed -e 's/^\.target sm_70$/.target sm_61/' "$out/kernels_sm70.ptx" > "$out/kernels_sm61.ptx"
grep -qx '\.target sm_61' "$out/kernels_sm61.ptx" \
    || { echo "sm_61 版文件头没改成功" >&2; exit 1; }
echo "已生成 $out/kernels_sm70.ptx（原文件头 $(grep -m1 '^\.version' "$src")）和 $out/kernels_sm61.ptx，入口："
grep -E '\.entry ' "$out/kernels_sm70.ptx" | sed -e 's/(.*//' -e 's/.*\.entry /  /'
