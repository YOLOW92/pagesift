// parse_long：自然语言写法，取文本里最靠前的一个

#[test]
fn table_parse_long() {
    const CASES: &[(&str, Option<&str>)] = &[
        ("March 5, 2024", Some("2024-03-05")),
        ("on March 5th, 2024 at noon", Some("2024-03-05")),
        ("SmithMarch 5, 2024", Some("2024-03-05")), // 粘在前一个词上的月份名
        ("5 March 2024", Some("2024-03-05")),
        ("5th of March, 2024", Some("2024-03-05")),
        ("2024 March 5", Some("2024-03-05")),
        ("2024年3月5日", Some("2024-03-05")),
        ("2024년 3월 5일", Some("2024-03-05")),
        // 多个日期取最靠前的
        ("March 5, 2024 (updated 1 April 2024)", Some("2024-03-05")),
        (
            "updated 1 April 2024, first March 5, 2024",
            Some("2024-04-01"),
        ),
        // 不合法或不是月份名
        ("February 30, 2024", None),
        ("Chapter 5, 2024", None),
        ("5 Foo 2024", None),
        ("March 2024", None),
        ("March 5, 1989", None), // YEAR 只认 1990–2039
        // 粘连规则的误报：普通英文词的结尾恰好是某种语言的月份缩写
        // 粘连只认大小写交界（0.80 前 "out"、"set" 被当成葡语 outubro、setembro 的缩写）
        ("about 5, 2024", None),
        ("sunset 5 2024", None),
        ("Updated:March 5, 2024", Some("2024-03-05")),
        ("JOHNMarch 5, 2024", None),
    ];
    check_opt("parse_long", CASES, |s| render(parse_long(s)));
}

