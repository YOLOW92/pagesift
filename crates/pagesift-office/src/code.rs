/// 没有扩展名的常见文件。
pub(crate) fn language_of_name(name: &str) -> Option<&'static str> {
    let base = name.rsplit(['/', '\\']).next().unwrap_or(name);
    Some(match base {
        "Makefile" | "makefile" | "GNUmakefile" | "BSDmakefile" => "makefile",
        "Dockerfile" | "Containerfile" => "dockerfile",
        "CMakeLists.txt" => "cmake",
        "Justfile" | "justfile" => "just",
        "Rakefile" | "Gemfile" | "Podfile" | "Brewfile" | "Vagrantfile" | "Fastfile" => "ruby",
        "BUILD" | "BUILD.bazel" | "WORKSPACE" | "MODULE.bazel" => "starlark",
        ".gitignore" | ".dockerignore" | ".npmignore" | ".eslintignore" => "gitignore",
        ".gitattributes" => "gitattributes",
        ".gitconfig" | ".gitmodules" => "git_config",
        "COMMIT_EDITMSG" => "gitcommit",
        "git-rebase-todo" => "git_rebase",
        ".bashrc" | ".zshrc" | ".profile" | ".bash_profile" | ".zprofile" => "bash",
        ".env" | ".env.local" | ".env.example" => "dotenv",
        ".editorconfig" => "editorconfig",
        "go.mod" => "gomod",
        "go.sum" => "gosum",
        "go.work" => "gowork",
        "Earthfile" => "earthfile",
        "Kconfig" => "kconfig",
        "meson.build" | "meson_options.txt" => "meson",
        "requirements.txt" | "constraints.txt" => "requirements",
        "MANIFEST.in" => "pymanifest",
        "Pipfile" | "Cargo.lock" | "poetry.lock" | "uv.lock" => "toml",
        "tmux.conf" | ".tmux.conf" => "tmux",
        ".inputrc" => "readline",
        "qmldir" => "qmldir",
        "kitty.conf" => "kitty",
        "hyprland.conf" => "hyprlang",
        ".XCompose" => "xcompose",
        "ssh_config" | "sshd_config" => "ssh_config",
        "nginx.conf" => "nginx",
        "Caddyfile" => "caddy",
        "Jenkinsfile" => "groovy",
        "Procfile" => "bash",
        _ => return None,
    })
}

