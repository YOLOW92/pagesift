/// 标准表 B.n；每张表第一次用到时建一次。
pub(super) fn get(n: u8) -> Result<&'static Table, String> {
    static TABLES: [OnceLock<Table>; ROWS.len()] = [const { OnceLock::new() }; ROWS.len()];
    let i = usize::from(n)
        .checked_sub(1)
        .filter(|&i| i < ROWS.len())
        .ok_or_else(|| format!("没有标准霍夫曼表 B.{n}"))?;
    if let Some(t) = TABLES[i].get() {
        return Ok(t);
    }
    let t = Table::build(ROWS[i]).map_err(|e| format!("标准表 B.{n}：{e}"))?;
    Ok(TABLES[i].get_or_init(|| t))
}
